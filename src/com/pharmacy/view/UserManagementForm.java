    private void btnAddUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddUserActionPerformed
        String fullName = JOptionPane.showInputDialog(this, "Enter Staff Full Name:");
    if (fullName == null || fullName.trim().isEmpty()) return;

    String username = JOptionPane.showInputDialog(this, "Enter Username:");
    if (username == null || username.trim().isEmpty()) return;

    String password = JOptionPane.showInputDialog(this, "Enter Password:");
    if (password == null || password.trim().isEmpty()) return;

    String roleIdStr = JOptionPane.showInputDialog(this, "Enter Role ID (1 for Admin, 2 for Cashier):");
    if (roleIdStr == null || roleIdStr.trim().isEmpty()) return;

    String query = "INSERT INTO users (full_name, username, password, role_id) VALUES (?, ?, ?, ?)";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pstmt = conn.prepareStatement(query)) {
        
        pstmt.setString(1, fullName.trim());
        pstmt.setString(2, username.trim());
        pstmt.setString(3, password.trim());
        pstmt.setInt(4, Integer.parseInt(roleIdStr.trim()));
        
        int inserted = pstmt.executeUpdate();
        if (inserted > 0) {
            JOptionPane.showMessageDialog(this, "User account created successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            loadUserData(); // Refresh table
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Role ID must be a valid number.", "Input Error", JOptionPane.ERROR_MESSAGE);
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Database error (Username might already exist): " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }// TODO add your handling code here:
    }//GEN-LAST:event_btnAddUserActionPerformed

    private void btnUpdateUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateUserActionPerformed
     int selectedRow = tableUsers.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please select a user from the table first.", "Selection Required", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int userId = (int) tableUsers.getValueAt(selectedRow, 0);
    String currentName = tableUsers.getValueAt(selectedRow, 1).toString();

    String newPassword = JOptionPane.showInputDialog(this, "Enter new password for " + currentName + ":");
    if (newPassword == null || newPassword.trim().isEmpty()) return;

    String query = "UPDATE users SET password = ? WHERE user_id = ?";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pstmt = conn.prepareStatement(query)) {
        
        pstmt.setString(1, newPassword.trim());
        pstmt.setInt(2, userId);
        
        int updated = pstmt.executeUpdate();
        if (updated > 0) {
            JOptionPane.showMessageDialog(this, "Password updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            loadUserData();
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }   // TODO add your handling code here:
    }//GEN-LAST:event_btnUpdateUserActionPerformed

    private void btnDeleteUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteUserActionPerformed
int selectedRow = tableUsers.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please select a user to delete.", "Selection Required", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int userId = (int) tableUsers.getValueAt(selectedRow, 0);
    String username = tableUsers.getValueAt(selectedRow, 2).toString();

    int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete user '" + username + "'?", "Confirm Deletion", JOptionPane.YES_NO_OPTION);
    if (confirm != JOptionPane.YES_OPTION) return;

    String query = "DELETE FROM users WHERE user_id = ?";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pstmt = conn.prepareStatement(query)) {
        
        pstmt.setInt(1, userId);
        int deleted = pstmt.executeUpdate();
        if (deleted > 0) {
            JOptionPane.showMessageDialog(this, "User deleted successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            loadUserData(); // Refresh table
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteUserActionPerformed

