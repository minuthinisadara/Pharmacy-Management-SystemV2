    private void loadInventoryData() {
    DefaultTableModel model = (DefaultTableModel) tableProducts.getModel();
    model.setRowCount(0); // Clear existing table rows

    String query = "SELECT p.product_id, p.product_name, c.category_name, p.unit_price, p.stock_quantity, p.expiry_date " +
                   "FROM products p LEFT JOIN categories c ON p.category_id = c.category_id";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pstmt = conn.prepareStatement(query);
         ResultSet rs = pstmt.executeQuery()) {

        while (rs.next()) {
            Object[] row = {
                rs.getInt("product_id"),
                rs.getString("product_name"),
                rs.getString("category_name"),
                rs.getDouble("unit_price"),
                rs.getInt("stock_quantity"),
                rs.getDate("expiry_date")
            };
            model.addRow(row);
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error loading inventory: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
    }
}
    
