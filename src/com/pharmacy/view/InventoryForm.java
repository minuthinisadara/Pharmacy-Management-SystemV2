    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
String keyword = txtSearch.getText().trim();
    DefaultTableModel model = (DefaultTableModel) tableProducts.getModel();
    model.setRowCount(0);

    String query = "SELECT p.product_id, p.product_name, c.category_name, p.unit_price, p.stock_quantity, p.expiry_date " +
                   "FROM products p LEFT JOIN categories c ON p.category_id = c.category_id " +
                   "WHERE p.product_name LIKE ?";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pstmt = conn.prepareStatement(query)) {
        
        pstmt.setString(1, "%" + keyword + "%");
        
        try (ResultSet rs = pstmt.executeQuery()) {
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("product_id"),
                    rs.getString("product_name"),
                    rs.getString("category_name"),
                    rs.getDouble("unit_price"),
                    rs.getInt("stock_quantity"),
                    rs.getDate("expiry_date")
                });
            }
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Search error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
   // 1. Prompt user for all required database fields matching your schema
        String productCode = JOptionPane.showInputDialog(this, "Enter Product Code (e.g., MED009):");
        if (productCode == null || productCode.trim().isEmpty()) return;

        String productName = JOptionPane.showInputDialog(this, "Enter Product Name:");
        if (productName == null || productName.trim().isEmpty()) return;

        String categoryStr = JOptionPane.showInputDialog(this, "Enter Category ID (e.g., 1, 2, 3):");
        if (categoryStr == null || categoryStr.trim().isEmpty()) return;

        String supplierStr = JOptionPane.showInputDialog(this, "Enter Supplier ID (e.g., 1, 2, 3):");
        if (supplierStr == null || supplierStr.trim().isEmpty()) return;

        String priceStr = JOptionPane.showInputDialog(this, "Enter Unit Price (Selling Price):");
        if (priceStr == null || priceStr.trim().isEmpty()) return;

        String costPriceStr = JOptionPane.showInputDialog(this, "Enter Cost Price:");
        if (costPriceStr == null || costPriceStr.trim().isEmpty()) return;

        String qtyStr = JOptionPane.showInputDialog(this, "Enter Stock Quantity:");
        if (qtyStr == null || qtyStr.trim().isEmpty()) return;

        String reorderStr = JOptionPane.showInputDialog(this, "Enter Reorder Level (e.g., 20):");
        if (reorderStr == null || reorderStr.trim().isEmpty()) return;

        String expiryStr = JOptionPane.showInputDialog(this, "Enter Expiry Date (YYYY-MM-DD):");
        if (expiryStr == null || expiryStr.trim().isEmpty()) return;

        // 2. Full SQL INSERT statement matching all columns
        String query = "INSERT INTO products (product_code, product_name, category_id, supplier_id, unit_price, cost_price, stock_quantity, reorder_level, expiry_date) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(query)) {
            
            pstmt.setString(1, productCode.trim());
            pstmt.setString(2, productName.trim());
            pstmt.setInt(3, Integer.parseInt(categoryStr.trim()));
            pstmt.setInt(4, Integer.parseInt(supplierStr.trim()));
            pstmt.setDouble(5, Double.parseDouble(priceStr.trim()));
            pstmt.setDouble(6, Double.parseDouble(costPriceStr.trim()));
            pstmt.setInt(7, Integer.parseInt(qtyStr.trim()));
            pstmt.setInt(8, Integer.parseInt(reorderStr.trim()));
            pstmt.setString(9, expiryStr.trim());
            
            int rowsInserted = pstmt.executeUpdate();
            if (rowsInserted > 0) {
                JOptionPane.showMessageDialog(this, "Product added successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                loadInventoryData(); // Refresh table automatically
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter valid numeric values for IDs, prices, quantities, or reorder levels.", "Input Error", JOptionPane.ERROR_MESSAGE);
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
// 1. Check if a row is selected in the table
    int selectedRow = tableProducts.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please select a product from the table to update.", "Selection Required", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 2. Grab the product_id and existing values from the selected row
    int productId = (int) tableProducts.getValueAt(selectedRow, 0);
    String currentName = tableProducts.getValueAt(selectedRow, 1).toString();
    Object currentPrice = tableProducts.getValueAt(selectedRow, 3);
    Object currentStock = tableProducts.getValueAt(selectedRow, 4);

    // 3. Prompt user for updated details (pre-filled with current values)
    String newName = JOptionPane.showInputDialog(this, "Update Product Name:", currentName);
    if (newName == null) return; // User clicked Cancel

    String newPriceStr = JOptionPane.showInputDialog(this, "Update Unit Price:", currentPrice);
    if (newPriceStr == null) return;

    String newStockStr = JOptionPane.showInputDialog(this, "Update Stock Quantity:", currentStock);
    if (newStockStr == null) return;

    // 4. Execute the SQL UPDATE statement
    String query = "UPDATE products SET product_name = ?, unit_price = ?, stock_quantity = ? WHERE product_id = ?";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pstmt = conn.prepareStatement(query)) {
        
        pstmt.setString(1, newName.trim());
        pstmt.setDouble(2, Double.parseDouble(newPriceStr.trim()));
        pstmt.setInt(3, Integer.parseInt(newStockStr.trim()));
        pstmt.setInt(4, productId);
        
        int rowsUpdated = pstmt.executeUpdate();
        if (rowsUpdated > 0) {
            JOptionPane.showMessageDialog(this, "Product updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            loadInventoryData(); // Refresh table automatically
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Please enter valid numeric values for price and stock quantity.", "Input Error", JOptionPane.ERROR_MESSAGE);
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
// 1. Check if a row is selected in the table
    int selectedRow = tableProducts.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please select a product from the table to delete.", "Selection Required", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 2. Grab the product_id and product name from the selected row
    int productId = (int) tableProducts.getValueAt(selectedRow, 0);
    String productName = tableProducts.getValueAt(selectedRow, 1).toString();

    // 3. Ask for user confirmation before deleting
    int confirm = JOptionPane.showConfirmDialog(
        this, 
        "Are you sure you want to delete '" + productName + "'?", 
        "Confirm Deletion", 
        JOptionPane.YES_NO_OPTION, 
        JOptionPane.WARNING_MESSAGE
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return; // User cancelled
    }

    // 4. Execute the SQL DELETE statement
    String query = "DELETE FROM products WHERE product_id = ?";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pstmt = conn.prepareStatement(query)) {
        
        pstmt.setInt(1, productId);
        
        int rowsDeleted = pstmt.executeUpdate();
        if (rowsDeleted > 0) {
            JOptionPane.showMessageDialog(this, "Product deleted successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            loadInventoryData(); // Refresh table automatically
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteActionPerformed

